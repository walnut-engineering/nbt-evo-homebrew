/* Scale factors for different font sizes - using clean integer multiples for crisp bitmap scaling */
static const float font_scales[EVO_FONT_COUNT] = {
    1.0f,    /* EVO_FONT_SMALL:   8x12  (1x scale) */
    2.0f,    /* EVO_FONT_MEDIUM:  16x24 (2x scale) - clean integer scaling */
    3.0f,    /* EVO_FONT_LARGE:   24x36 (3x scale) - clean integer scaling */
    3.0f,    /* EVO_FONT_XLARGE:  24x36 (3x scale) */
    4.0f     /* EVO_FONT_XXLARGE: 32x48 (4x scale) */
};

/* Base font dimensions (8x12) */
#define BASE_FONT_WIDTH  8
#define BASE_FONT_HEIGHT 12

/* ============================================================================
 * UTILITY FUNCTIONS
 * ============================================================================ */

evo_font_dimensions_t evo_text_get_font_dimensions(evo_font_size_t font_size) {
    evo_font_dimensions_t dims;
    
    if (font_size >= EVO_FONT_COUNT) {
        font_size = EVO_FONT_MEDIUM;  /* Default fallback */
    }
    
    float scale = font_scales[font_size];
    dims.width = (int)(BASE_FONT_WIDTH * scale);
    dims.height = (int)(BASE_FONT_HEIGHT * scale);
    
    return dims;
}

int evo_text_is_char_supported(char c) {
    return (c >= 32 && c <= 127);  /* Extended to include degree symbol at 127 */
}

int evo_text_get_text_width(const char *text, evo_font_size_t font_size) {
    if (!text) return 0;
    
    evo_font_dimensions_t dims = evo_text_get_font_dimensions(font_size);
    return strlen(text) * dims.width;
}

/* ============================================================================
 * CORE TEXT RENDERING FUNCTIONS
 * ============================================================================ */

int evo_text_draw_char(evo_graphics_context_t *ctx, int x, int y, 
                       char c, evo_font_size_t font_size, uint32_t color) {
    if (!ctx || !ctx->buffer) return 0;
    
    if (font_size >= EVO_FONT_COUNT) {
        font_size = EVO_FONT_MEDIUM;  /* Default fallback */
    }
    
    evo_font_dimensions_t dims = evo_text_get_font_dimensions(font_size);
    
    if (!evo_text_is_char_supported(c)) {
        c = '?';  /* Replace unsupported characters with question mark */
    }
    
    int char_index = c - 32;  /* ASCII offset */
    const uint8_t *font_data = font_8x12[char_index];
    
    float scale = font_scales[font_size];
    int scale_int = (int)scale;
    
    /* For non-integer scales (like 1.5x), we use smart scaling */
    if (scale != (float)scale_int) {
        /* Smart scaling for 1.5x - alternate between 1 and 2 pixel scaling */
        for (int row = 0; row < BASE_FONT_HEIGHT; row++) {
            uint8_t line = font_data[row];
            int scaled_row_height = (row % 2 == 0) ? 2 : 1;  /* Alternate row heights */
            
            for (int col = 0; col < BASE_FONT_WIDTH; col++) {
                if (line & (1 << (7 - col))) {
                    int scaled_col_width = (col % 2 == 0) ? 2 : 1;  /* Alternate col widths */
                    
                    /* Draw scaled pixel */
                    for (int sy = 0; sy < scaled_row_height; sy++) {
                        for (int sx = 0; sx < scaled_col_width; sx++) {
                            int px = x + (col * 3) / 2 + sx;  /* Approximate 1.5x scaling */
                            int py = y + (row * 3) / 2 + sy;
                            
                            if (px >= 0 && px < ctx->width && py >= 0 && py < ctx->height) {
                                ctx->buffer[py * ctx->width + px] = color;
                            }
                        }
                    }
                }
            }
        }
    } else {
        /* Integer scaling - simple and fast */
        for (int row = 0; row < BASE_FONT_HEIGHT; row++) {
            uint8_t line = font_data[row];
            for (int col = 0; col < BASE_FONT_WIDTH; col++) {
                if (line & (1 << (7 - col))) {
                    /* Draw scaled pixel */
                    for (int sy = 0; sy < scale_int; sy++) {
                        for (int sx = 0; sx < scale_int; sx++) {
                            int px = x + col * scale_int + sx;
                            int py = y + row * scale_int + sy;
                            
                            if (px >= 0 && px < ctx->width && py >= 0 && py < ctx->height) {
                                ctx->buffer[py * ctx->width + px] = color;
                            }
                        }
                    }
                }
            }
        }
    }
    
    return dims.width;
}

int evo_text_draw_text(evo_graphics_context_t *ctx, int x, int y, 
                       const char *text, evo_font_size_t font_size, uint32_t color) {
    if (!ctx || !text) return 0;
    
    int current_x = x;
    while (*text) {
        current_x += evo_text_draw_char(ctx, current_x, y, *text, font_size, color);
        text++;
    }
    
    return current_x - x;
}

int evo_text_draw_text_with_background(evo_graphics_context_t *ctx, int x, int y, 
                                       const char *text, evo_font_size_t font_size, 
                                       uint32_t text_color, uint32_t bg_color) {
    if (!ctx || !text) return 0;
    
    /* Calculate text dimensions */
    evo_font_dimensions_t dims = evo_text_get_font_dimensions(font_size);
    int text_width = evo_text_get_text_width(text, font_size);
    
    /* Draw background rectangle */
    for (int py = y; py < y + dims.height; py++) {
        for (int px = x; px < x + text_width; px++) {
            if (px >= 0 && px < ctx->width && py >= 0 && py < ctx->height) {
                ctx->buffer[py * ctx->width + px] = bg_color;
            }
        }
    }
    
    /* Draw text on top */
    return evo_text_draw_text(ctx, x, y, text, font_size, text_color);
}

int evo_text_draw_text_aligned(evo_graphics_context_t *ctx, int x, int y, 
                               const char *text, evo_font_size_t font_size,
                               uint32_t color, evo_text_align_t alignment, int max_width) {
    if (!ctx || !text) return 0;
    
    int text_width = evo_text_get_text_width(text, font_size);
    int draw_x = x;
    
    switch (alignment) {
        case EVO_TEXT_ALIGN_CENTER:
            draw_x = x + (max_width - text_width) / 2;
            break;
        case EVO_TEXT_ALIGN_RIGHT:
            draw_x = x + max_width - text_width;
            break;
        case EVO_TEXT_ALIGN_LEFT:
        default:
            draw_x = x;
            break;
    }
    
    return evo_text_draw_text(ctx, draw_x, y, text, font_size, color);
}

int evo_text_draw_text_formatted(evo_graphics_context_t *ctx, int x, int y, 
                                 evo_font_size_t font_size, uint32_t color, 
                                 const char *format, ...) {
    if (!ctx || !format) return 0;
    
    char buffer[256];
    va_list args;
    va_start(args, format);
    vsnprintf(buffer, sizeof(buffer), format, args);
    va_end(args);
    
    return evo_text_draw_text(ctx, x, y, buffer, font_size, color);
}

int evo_text_draw_progress_text(evo_graphics_context_t *ctx, int bar_x, int bar_y,
                                int bar_width, int bar_height, const char *text,
                                evo_font_size_t font_size, uint32_t color) {
    if (!ctx || !text) return 0;
    
    evo_font_dimensions_t dims = evo_text_get_font_dimensions(font_size);
    int text_width = evo_text_get_text_width(text, font_size);
    
    /* Center text within the progress bar */
    int text_x = bar_x + (bar_width - text_width) / 2;
    int text_y = bar_y + (bar_height - dims.height) / 2;
    
    return evo_text_draw_text(ctx, text_x, text_y, text, font_size, color);
}
