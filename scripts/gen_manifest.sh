#!/bin/sh
# gen_manifest.sh - generate the launcher manifest from projects/*/app.desc.
#
# Single source of truth: each project that is a launcher tile has an app.desc.
# This scans them, sorts by `order`, and writes build/launcher.manifest in the
# launcher's "Name|command|icon" line format (with on-unit absolute paths).
#
#   ./scripts/gen_manifest.sh            # write build/launcher.manifest + print
#
# Add a tile = drop an app.desc in a project. Remove = delete it or set
# enabled = 0. No central file to hand-edit. A project that makes more than one
# tile names its descriptors app.<something>.desc (see projects/evo_retro).
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
. "$HERE/evo_env.sh"

mkdir -p "$BUILD_DIR"
tmp="$BUILD_DIR/.manifest.tmp.$$"
: > "$tmp"

n=0
for desc in "$PROJECTS"/*/app.desc "$PROJECTS"/*/app.*.desc; do
  [ -f "$desc" ] || continue
  read_desc "$desc"
  [ "$D_enabled" = "0" ] && continue
  if [ -z "$D_name" ] || [ -z "$D_exec" ]; then
    echo "  ! $desc: missing name or exec, skipped" >&2
    continue
  fi
  cmd="$(evo_onunit "$D_exec")"
  icon="$(evo_onunit_icon "$D_icon")"
  # sortable: zero-padded order, then the manifest line
  printf '%010d|%s|%s|%s\n' "$D_order" "$D_name" "$cmd" "$icon" >> "$tmp"
  n=$((n + 1))
done

{
  echo "# Generated by scripts/gen_manifest.sh from projects/*/app.desc - do not edit by hand."
  echo "# One tile per line:  Name|command|icon"
  sort "$tmp" | sed 's/^[0-9]*|//'
} > "$MANIFEST"
rm -f "$tmp"

echo "wrote $MANIFEST ($n tiles):" >&2
sed 's/^/  /' "$MANIFEST" >&2
